// Build the same core C calendar, then package a self-contained browser module.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(process.argv[2]??join(root,'janus'));
mkdirSync(output,{recursive:true});
const cc=process.env.WASM_CC??(process.env.WASI_SDK_PATH ? join(process.env.WASI_SDK_PATH,'bin/clang') : 'clang');
const exports=['janus_abi','janus_call','janus_kind','janus_scalar','janus_count','janus_key','janus_text','janus_number'];
const args=['--target=wasm32-wasip1','-std=c11','-Wall','-Wextra','-Werror','-Oz','-ffp-contract=off','-fno-fast-math',
  '-DAM_CALENDAR_ONLY','-Icore','core/ariannamethod.c','janus/calendar_wasm.c',
  '-nostartfiles','-Wl,--no-entry','-Wl,--strip-all','-Wl,--export-memory',
  '-Wl,--initial-memory=131072','-Wl,--max-memory=131072',...exports.map(x=>`-Wl,--export=${x}`),
  '-lm','-o',join(output,'calendar.wasm')];
const built=spawnSync(cc,args,{cwd:root,encoding:'utf8'});
if(built.error || built.status!==0) {
  process.stderr.write(built.stderr??'');
  throw built.error??new Error('calendar WASM compilation failed; set WASI_SDK_PATH or WASM_CC');
}
const bytes=readFileSync(join(output,'calendar.wasm'));
const module=new WebAssembly.Module(bytes);
if(WebAssembly.Module.imports(module).length) throw new Error('calendar binary has host imports');
const paths=['core/ariannamethod.c','core/ariannamethod.h','janus/calendar_wasm.c','janus/calendar.mjs','janus/calendar_wasm.mjs','tools/build_calendar_wasm.mjs'];
const hash=createHash('sha256');
for(const path of paths) hash.update(path+'\0').update(readFileSync(join(root,path))).update('\0');
const sourceHash=hash.digest('hex'),wasmHash=createHash('sha256').update(bytes).digest('hex');
const base=readFileSync(join(root,'janus/calendar.mjs'),'utf8');
const adapter=readFileSync(join(root,'janus/calendar_wasm.mjs'),'utf8').replace(/^import .* from '\.\/calendar\.mjs';\n/m,'');
const bundle=`// Generated by tools/build_calendar_wasm.mjs. Source SHA-256: ${sourceHash}\n`+
  `// WASM SHA-256: ${wasmHash}. LGPL-3.0-or-later.\n`+base+'\n'+adapter+
  `\nconst CALENDAR_WASM_BASE64='${bytes.toString('base64')}';\n`+
  `export function bundledBytes() { return Uint8Array.from(atob(CALENDAR_WASM_BASE64),c=>c.charCodeAt(0)); }\n`+
  `export async function bundledCalendar() { return wasmCalendar(bundledBytes()); }\n`;
writeFileSync(join(output,'calendar_browser.mjs'),bundle);
const html=`<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>JANUS.CALENDAR · Offline</title><style>body{font:16px system-ui;max-width:800px;margin:3rem auto;padding:0 1rem;background:#151a20;color:#e7e0d4}input,button{font:inherit;padding:.5rem;background:#242c34;color:inherit;border:1px solid #85958f}input{width:5rem}pre{white-space:pre-wrap;overflow-wrap:anywhere}h1{font-weight:400}</style>
<h1>JANUS.CALENDAR</h1><p>One date. Two calendars. A personal origin.</p>
<form id="query"><label>Year <input name="year" type="number" value="2026" required></label> <label>Month <input name="month" type="number" value="10" required></label> <label>Day <input name="day" type="number" value="4" required></label> <button>Read date</button></form>
<pre id="result" aria-live="polite">Loading calendar…</pre>
<script type="module">\n${bundle}\nconst calendar=await bundledCalendar();
async function show(){try{const form=document.querySelector('#query');const day=await calendar.gregorian(+form.elements.year.value,+form.elements.month.value,+form.elements.day.value);document.querySelector('#result').textContent=JSON.stringify(await calendar.subject(498,day),null,2);document.documentElement.dataset.ready='true';}catch(error){document.querySelector('#result').textContent=error.message;}}
document.querySelector('#query').addEventListener('submit',event=>{event.preventDefault();show();});await show();\n</script></html>\n`;
writeFileSync(join(output,'calendar-offline.html'),html);
console.log(`JANUS.CALENDAR WASM: ${bytes.length} bytes; no host imports; source ${sourceHash}`);
