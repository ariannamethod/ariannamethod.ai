#!/usr/bin/env python3
"""Check AML fixed text against Python formatting of exact binary32 values.

The oracle decodes each 32-bit word to a Python float (an exact promotion), then
uses Python's fixed-format nearest/ties-even conversion. Decimal source literals
in the frozen C/runtime fixture spell the complete binary32 value, so they are
exact under every floating-point rounding mode.
"""
import argparse
import ctypes
from decimal import Decimal
from pathlib import Path
import random
import struct


def value(bits):
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def bits(number):
    return struct.unpack("<I", struct.pack("<f", number))[0]


def fixtures():
    words = {0, 1, 2, 0x007fffff, 0x00800000, 0x00800001,
             0x7f7ffffe, 0x7f7fffff}
    # Includes both sides of decimal rounding boundaries, exact binary half
    # ties, integer carry and the boundary where float32 spacing exceeds one.
    for number in (0.05, 0.15, 0.45, 0.65, 0.85, 0.5, 1.5, 2.5, 3.5,
                   1.25, 1.75, 0.125, 0.375, 0.625, 0.875, 9.9995,
                   0.0000000005, 16777216):
        center = bits(number)
        words.update((center - 1, center, center + 1))
    for word in sorted(words):
        for signed in (word, word | 0x80000000):
            for digits in (0, 1, 2, 3, 9):
                yield signed, digits


def write_fixture(path):
    rows = ["/* Generated by tools/verify_text_fixed.py: exact binary32 -> Python format. */",
            "static const struct { uint32_t bits; int digits; const char* literal;",
            "                      const char* expected; } fixed_cases[] = {"]
    for word, digits in fixtures():
        exact = format(Decimal.from_float(value(word)), "f")
        expected = format(value(word), f".{digits}f")
        rows.append(f'    {{0x{word:08x}u, {digits}, "{exact}", "{expected}"}},')
    rows.append("};\n")
    path.write_text("\n".join(rows))


class String(ctypes.Structure):
    _fields_ = [("data", ctypes.c_void_p), ("byte_len", ctypes.c_int),
                ("len", ctypes.c_int), ("refcount", ctypes.c_int)]


def check_library(path):
    lib = ctypes.CDLL(str(path.resolve()))
    lib.am_string_fixed.argtypes = [ctypes.c_float, ctypes.c_int]
    lib.am_string_fixed.restype = ctypes.POINTER(String)
    lib.am_string_free.argtypes = [ctypes.POINTER(String)]
    words = {word for word, _ in fixtures()}
    # Every exponent and both signs, selected significand extremes, then a
    # reproducible sample across the entire bit space; every precision 0..9.
    for exponent in range(255):
        for mantissa in (0, 1, 0x3fffff, 0x7ffffe, 0x7fffff):
            for sign in (0, 0x80000000):
                words.add(sign | (exponent << 23) | mantissa)
    stream = random.Random(0xA71A2026)
    for _ in range(8192):
        word = stream.getrandbits(32)
        if (word >> 23) & 255 != 255:
            words.add(word)
    count = 0
    for word in sorted(words):
        number = value(word)
        for digits in range(10):
            result = lib.am_string_fixed(number, digits)
            assert result, (hex(word), digits, "null result")
            try:
                actual = ctypes.string_at(result.contents.data).decode("ascii")
                expected = format(number, f".{digits}f")
                assert actual == expected, (hex(word), digits, actual, expected)
                assert result.contents.byte_len == result.contents.len == len(expected)
                assert result.contents.refcount == 1
                count += 1
            finally:
                lib.am_string_free(result)
    print(f"PASS exact-binary32 Python oracle: {count} values, all 255 finite exponents, both signs, 10 precisions")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--write-fixtures", type=Path)
    parser.add_argument("--library", type=Path)
    args = parser.parse_args()
    if not args.write_fixtures and not args.library:
        parser.error("provide --write-fixtures and/or --library")
    if args.write_fixtures:
        write_fixture(args.write_fixtures)
    if args.library:
        check_library(args.library)
